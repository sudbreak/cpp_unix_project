#!/bin/bash
# Скрипт полного отката к текущей ревизии

echo " Все несохранённые изменения и неотслеживаемые файлы будут удалены!"
read -p "Продолжить? (y/N): " confirm

if [[ "$confirm" == "y" || "$confirm" == "Y" ]]; then
    echo "Откат отслеживаемых изменений..."
    git reset --hard

    echo "Удаление неотслеживаемых файлов и папок..."
    git clean -fd

    echo " Рабочее состояние восстановлено до текущей ревизии."
else
    echo " Операция отменена."
fi
